import { test, expect as baseExpect } from '@playwright/test';
const expect = baseExpect.configure({ timeout: 30_000 });

test('persistent workspace reopens edits, rejects a second tab, and runs Vite', async ({ page, context, browserName }, testInfo) => {
  test.skip(browserName !== 'chromium', 'Initial workspace acceptance browser is Chromium');
  await page.goto('/workspace/');
  await expect(page.getByRole('status')).toHaveText('Saved · revision 0');
  const editor = page.getByRole('textbox', { name: 'File contents' });
  const original = (await editor.textContent())!;
  await editor.fill(original.replace('Browser-built React', 'Persistent workspace'));
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.getByRole('status')).toHaveText('Saved · revision 1');
  const other = await context.newPage(); await other.goto('/workspace/');
  await expect(other.getByRole('status')).toContainText('open in another tab');
  await other.close();
  await page.reload();
  await expect(page.getByRole('status')).toHaveText('Saved · revision 1');
  await expect(editor).toContainText('Persistent workspace');
  await page.getByRole('button', { name: 'Check types', exact: true }).click();
  await expect(page.getByRole('status')).toHaveText('0 diagnostics');
  await page.getByRole('button', { name: 'Start preview', exact: true }).click();
  const preview = page.frameLocator('iframe[title="Project preview"]');
  await expect(preview.getByRole('heading')).toHaveText('Persistent workspace');
  await page.getByRole('button', { name: 'Build', exact: true }).click();
  await expect(page.getByLabel('Build status')).toHaveText('Build passed · revision 1');
  await editor.fill("import { message } from './message';\nconst wrong: number = message;\nexport default function App() { return <h1>{message}</h1>; }");
  await page.getByRole('button', { name: 'Check types', exact: true }).click();
  await expect(page.getByLabel('Diagnostics')).toContainText("Type 'string' is not assignable to type 'number'");
  await editor.fill("import { message } from './message';\nexport default function App() { return <h1>{message}</h1>; }");
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.getByRole('status')).toHaveText('Saved · revision 2');
  await expect(preview.getByRole('heading')).toHaveText('Original imported value');
  await page.getByRole('button', { name: 'Check types', exact: true }).click();
  await expect(page.getByRole('status')).toHaveText('0 diagnostics');
  await editor.press('ControlOrMeta+Home');
  for (let i = 0; i < 11; i++) await editor.press('ArrowRight');
  await page.getByRole('button', { name: 'Go to definition', exact: true }).click();
  await expect(page.getByRole('combobox', { name: 'File', exact: true })).toHaveValue('src/message.ts');
  await expect(editor).toContainText('Original imported value');
  await page.getByRole('combobox', { name: 'File', exact: true }).selectOption('src/App.tsx');
  await page.locator('.cm-line').first().hover({ position: { x: 90, y: 8 } });
  await expect(page.locator('.cm-tooltip-hover')).toContainText('message: string');
  await page.screenshot({ path: testInfo.outputPath('workspace-desktop.png'), fullPage: true });
  await editor.fill("import { message } from './message';\nmessage.");
  await editor.press('Control+Space');
  await expect(page.getByRole('option').filter({ hasText: /^charAt$/ })).toBeVisible();
  await page.keyboard.press('Escape');
  await page.setViewportSize({ width: 375, height: 812 });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: testInfo.outputPath('workspace-mobile.png'), fullPage: true });
});

test('related startup, build and save requests keep consistent visible job feedback', async ({ page, browserName }, testInfo) => {
  test.skip(browserName !== 'chromium', 'Initial workspace acceptance browser is Chromium');
  await page.goto('/workspace/');
  await expect(page.getByRole('status')).toHaveText('Saved · revision 0');
  await page.evaluate(() => {
    const seen: string[] = [];
    Object.assign(window, { taskFeedback: seen });
    new MutationObserver(() => seen.push([...document.querySelectorAll('[role=status], section[aria-label="Project tasks"] p')].map(node => node.textContent).join('\n')))
      .observe(document.querySelector('#app')!, { childList: true, subtree: true });
  });
  await page.getByRole('button', { name: 'Start preview', exact: true }).dblclick();
  await expect(page.getByRole('button', { name: 'Start preview', exact: true })).toBeDisabled();
  await page.getByRole('button', { name: 'Build', exact: true }).click();
  await expect(page.getByLabel('Build status')).toHaveText('Build queued · revision 0');
  await expect(page.getByRole('status')).toHaveText('Saved · revision 0');
  await page.getByRole('button', { name: 'Cancel build', exact: true }).click();
  await expect(page.getByLabel('Build status')).toHaveText('Build cancelled');
  await page.getByRole('button', { name: 'Build', exact: true }).dblclick();
  await expect(page.getByRole('button', { name: 'Build', exact: true })).toBeDisabled();
  const editor = page.getByRole('textbox', { name: 'File contents' });
  await editor.fill((await editor.innerText()).replace('Browser-built React', 'Updated during startup'));
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.getByRole('status')).toHaveText('Saved · revision 1');
  await expect(page.getByLabel('Build status')).toHaveText('Build passed · revision 0');
  await expect(page.getByLabel('Preview status')).toHaveText('Preview ready · revision 1');
  await expect(page.frameLocator('iframe[title="Project preview"]').getByRole('heading')).toHaveText('Updated during startup');
  await expect(page.getByRole('status')).toHaveText('Saved · revision 1');
  const feedback = await page.evaluate(() => (window as any).taskFeedback as string[]);
  expect(feedback.join('\n')).not.toMatch(/AbortError|superseded|failed:/);
  expect(feedback.join('\n')).toContain('Installing project dependencies');
  await testInfo.attach('job-feedback', { body: feedback.join('\n---\n'), contentType: 'text/plain' });
  await editor.press('ControlOrMeta+Home');
  await page.screenshot({ path: testInfo.outputPath('related-jobs.png'), fullPage: true });
});
